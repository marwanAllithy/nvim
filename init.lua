local function source_matugen()
  local matugen_path = os.getenv("HOME") .. "/.config/nvim/generated.lua"
  local file, err = io.open(matugen_path, "r")
  if err ~= nil then
    vim.cmd("colorscheme base16-catppuccin-mocha")
  else
    dofile(matugen_path)
    io.close(file)
  end
end

source_matugen()

